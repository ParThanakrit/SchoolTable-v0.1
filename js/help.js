  function showPageHelp(pageName) {
    var help = helpContent[pageName];
    if (!help) return;
    var extra = '';
    if (help.tips && help.tips.length) {
      extra = '<div class="dialog-detail"><b>เคล็ดลับ</b><ul class="list-plain">' +
        help.tips.map(function (tip) { return '<li><code>' + U.esc(tip.selector) + '</code> — ' + U.esc(tip.text) + '</li>'; }).join('') +
        '</ul></div>';
    }
    U.explainDialog({
      title: '❓ ' + help.title,
      cause: help.text,
      fix: '',
      extra: extra,
      closeText: 'ปิด'
    });
  }

